const savedLanguage = typeof window !== 'undefined' ? localStorage.getItem('arogya_language') || 'en' : 'en';

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: savedLanguage,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
  });

i18n.on('languageChanged', (lng) => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('arogya_language', lng);
    document.documentElement.lang = lng;
  }
});

export default i18n;
